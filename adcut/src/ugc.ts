export type ReferenceRole = 'character' | 'product' | 'location' | 'prop' | 'style' | 'other'
export type ShotSize = 'close-up' | 'medium' | 'wide' | 'over-the-shoulder' | 'top-down' | 'macro'
export type CameraMovement = 'static' | 'handheld' | 'slow-push-in' | 'pan' | 'tracking' | 'overhead'

/** One shot of the ad (usually 5 seconds). Several shots can belong to one generated "video" (block). */
export interface Scene {
  id: string
  title: string
  /** 1-based number of the generated video this shot belongs to */
  block: number
  duration: number
  visual: string
  dialogue: string
  /** on-screen text; added in the editor, not generated by the AI */
  overlay: string
  delivery: string
  /** optional extra prompt text on top of the visual description */
  prompt: string
  referenceIds: string[]
  /** the generated clip (or photo) you imported for this shot */
  primaryAssetId: string
  /** optional voice-over audio file for this shot */
  voiceAssetId: string
  shotSize: ShotSize
  cameraMovement: CameraMovement
  lighting: string
  framing: string
  continuity: string
  extraInstructions: string
  endFrame: string
}

/** Text that belongs to one generated video, taken from the REFERENCES / CONTINUITY / END FRAME sections. */
export interface BlockInfo {
  references: string
  continuity: string
  endFrame: string
}

export interface ReferenceSettings {
  role: ReferenceRole
  strength: number
  instructions: string
}

export interface PromptOptions {
  /** one prompt per 5s shot, or one prompt per generated video (all shots of the block) */
  mode: 'shot' | 'block'
  style: 'detailed' | 'compact'
  includeDialogue: boolean
  /** ask the AI to render the on-screen text itself (not recommended: AI garbles text, especially Hindi) */
  bakeText: boolean
}

export interface Parsed {
  scenes: Scene[]
  blocks: BlockInfo[]
  format: string
  negative: string
}

