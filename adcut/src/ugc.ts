export interface PromptContext {
  scenes: Scene[]
  blocks: BlockInfo[]
  format: string
  negative: string
  assets: Record<string, Asset>
  refs: Record<string, ReferenceSettings>
  opts: PromptOptions
}

const hasDevanagari = (s: string) => /[ऀ-ॿ]/.test(s)

function groupFor(ctx: PromptContext, scene: Scene): Scene[] {
  return ctx.opts.mode === 'block' ? ctx.scenes.filter((s) => s.block === scene.block) : [scene]
}

/** All assets the AI tool needs to receive for these scenes, in a stable order. */
export function referencesFor(ctx: PromptContext, group: Scene[]) {
  const ids: string[] = []
  group.forEach((s) => s.referenceIds.forEach((id) => !ids.includes(id) && ctx.assets[id] && ids.push(id)))
  return ids.map((id) => {
    const asset = ctx.assets[id]
    const settings = ctx.refs[id] ?? defaultRefSettings(asset)
    return { asset, settings }
  })
}

function shotLines(ctx: PromptContext, group: Scene[]) {
  let t = 0
  return group.map((s) => {
    const from = t
    t += s.duration
    const speech = !ctx.opts.includeDialogue
      ? 'No speech in this shot.'
      : s.dialogue
        ? `The creator says this exact line${hasDevanagari(s.dialogue) ? ' in natural, conversational Hindi' : ''}: "${s.dialogue}"${s.delivery ? ` (Delivery: ${s.delivery})` : ''}`
        : 'No speech in this shot.'
    const lines = [
      `[${mmss(from)}–${mmss(t)}] ${s.visual || s.title}`,
      s.prompt ? `Extra direction: ${s.prompt}` : '',
      `Camera: ${s.shotSize}, ${CAMERA_MOVEMENTS.find((c) => c.value === s.cameraMovement)?.label ?? s.cameraMovement}. Lighting: ${s.lighting}. Framing: ${s.framing}`,
      speech,
      ctx.opts.bakeText && s.overlay ? `Show this on-screen text exactly: "${s.overlay}"` : '',
      s.extraInstructions ? `Also: ${s.extraInstructions}` : '',
    ]
    return lines.filter(Boolean).join('\n')
  })
}

export function promptTitle(ctx: PromptContext, scene: Scene) {
  const group = groupFor(ctx, scene)
  const total = group.reduce((a, s) => a + s.duration, 0)
  return ctx.opts.mode === 'block'
    ? `Video ${scene.block} (${group.length} shot${group.length > 1 ? 's' : ''}, ${total}s)`
    : scene.title
}

export function buildPrompt(ctx: PromptContext, sceneId: string): string {
  const scene = ctx.scenes.find((s) => s.id === sceneId) ?? ctx.scenes[0]
  if (!scene) return ''
  const group = groupFor(ctx, scene)
  const first = group[0]
  const last = group[group.length - 1]
  const block = ctx.blocks[scene.block - 1]
  const total = group.reduce((a, s) => a + s.duration, 0)
  const refs = referencesFor(ctx, group)

  // continuity: block text for the first shot of a video, "carry on" wording for later shots
  const idx = ctx.scenes.indexOf(first)
  const continuity = [
    first.continuity,
    ctx.opts.mode === 'shot' && idx > 0 && ctx.scenes[idx - 1].block === first.block
      ? 'Continue seamlessly from the previous shot: same room, outfit, lighting and product placement.'
      : '',
  ]
    .filter(Boolean)
    .join(' ')

  const endFrame = last.endFrame || (ctx.opts.mode === 'block' ? block?.endFrame : '') || ''
  const textRule = ctx.opts.bakeText
    ? 'Render the on-screen text exactly as written.'
    : 'Do not generate any captions, subtitles, titles or watermarks. Only the printed labels already on the product may appear; all other text is added later in the editor.'
  const negative = ctx.negative

  if (ctx.opts.style === 'compact') {
    const refRule = refs.length
      ? `Use the attached reference images: ${refs.map((r) => `${roleLabel(r.settings.role).toLowerCase()} (${strengthWord(r.settings.strength)})`).join(', ')}.`
      : ''
    return [
      ctx.format || 'Vertical 9:16 authentic smartphone UGC video.',
      refRule,
      continuity,
      shotLines(ctx, group)
        .map((l) => l.replace(/\n/g, ' '))
        .join(' '),
      endFrame ? `End frame: ${endFrame}` : '',
      textRule,
      negative ? `Avoid: ${negative}` : '',
    ]
      .filter(Boolean)
      .join(' ')
  }

  const out: string[] = []
  out.push('UGC VIDEO PROMPT')
  out.push(`${promptTitle(ctx, scene)} · ${total} seconds · 9:16 vertical`)
  out.push('')

  if (refs.length) {
    out.push('ATTACH THESE IMAGES IN THE GENERATOR FIRST:')
    refs.forEach((r, i) => out.push(`${i + 1}. ${r.asset.name} — ${roleLabel(r.settings.role)}`))
    out.push('')
    out.push('REFERENCE RULES:')
    refs.forEach((r) => {
      out.push(`- ${roleLabel(r.settings.role)} (${r.asset.name}): ${strengthWord(r.settings.strength)}. ${GUIDANCE[r.settings.role]}`)
      if (r.settings.instructions.trim()) out.push(`  Extra: ${r.settings.instructions.trim()}`)
    })
    if (block?.references) out.push(`- From your script: ${block.references}`)
  } else {
    out.push('REFERENCES: none selected. Select the character, product and location images for this shot.')
  }
  out.push('')
  out.push(`FORMAT: ${ctx.format || 'Vertical 9:16, authentic smartphone UGC, natural light.'}`)
  if (continuity) {
    out.push('')
    out.push(`CONTINUITY: ${continuity}`)
  }
  out.push('')
  out.push('SHOTS:')
  shotLines(ctx, group).forEach((l) => {
    out.push(l)
    out.push('')
  })
  out.push(`TEXT RULE: ${textRule}`)
  if (endFrame) out.push(`END FRAME: ${endFrame}`)
  if (negative) {
    out.push('')
    out.push(`AVOID: ${negative}`)
  }
  return out.join('\n').replace(/\n{3,}/g, '\n\n').trim()
}

/** Every prompt of the ad, one per shot or per generated video, ready to copy or download. */
export function buildPromptPack(ctx: PromptContext): { label: string; text: string }[] {
  const seen = new Set<number>()
  const list: { label: string; text: string }[] = []
  for (const s of ctx.scenes) {
    if (ctx.opts.mode === 'block') {
      if (seen.has(s.block)) continue
      seen.add(s.block)
    }
    list.push({ label: promptTitle(ctx, s), text: buildPrompt(ctx, s.id) })
  }
  return list
}
