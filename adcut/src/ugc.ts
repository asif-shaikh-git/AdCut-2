export function inferRole(name: string): ReferenceRole {
  const v = name.toLowerCase()
  if (/character|sheet|person|creator|model|woman|man|portrait|face|human|sara/.test(v)) return 'character'
  if (/product|kit|packaging|brand|candle|logo|label|box/.test(v)) return 'product'
  if (/location|living.?room|bedroom|kitchen|environment|interior|room|background|studio/.test(v)) return 'location'
  if (/style|moodboard|aesthetic|visual.?reference/.test(v)) return 'style'
  return 'other'
}

export const defaultRefSettings = (asset: Asset): ReferenceSettings => ({
  role: inferRole(asset.name),
  strength: 85,
  instructions: '',
})

export function strengthWord(strength: number) {
  return strength >= 85 ? 'must match exactly' : strength >= 65 ? 'match closely' : strength >= 40 ? 'follow loosely' : 'use as light inspiration'
}

const GUIDANCE: Record<ReferenceRole, string> = {
  character:
    'Keep the same identity: face, skin tone, eye colour, hairstyle or head covering, outfit and body proportions. Do not replace the person.',
  product:
    'Keep the real product: box shape, colours, label layout, logo, brand spelling and included items. Do not redesign or invent a different product.',
  location:
    'Use as the environment: same room layout, furniture, wall colour, window position and light direction.',
  prop: 'Keep the recognisable shape, colour and placement of this object.',
  style: 'Use for lighting, mood and colour treatment only; do not copy unrelated content.',
  other: 'Use the visible details wherever they are relevant to the shot.',
}

export function roleLabel(role: ReferenceRole) {
  return ROLE_OPTIONS.find((r) => r.value === role)?.label ?? role
}

