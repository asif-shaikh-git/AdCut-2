const toSec = (s: string) => {
  const p = s.split(':').map(Number)
  if (p.some(Number.isNaN)) return 0
  return p.length === 3 ? p[0] * 3600 + p[1] * 60 + p[2] : p.length === 2 ? p[0] * 60 + p[1] : p[0]
}

const mmss = (sec: number) => `${Math.floor(sec / 60)}:${String(Math.round(sec % 60)).padStart(2, '0')}`

const unquote = (s: string) =>
  s
    .trim()
    .replace(/^["“”«'‘]+/, '')
    .replace(/["“”»'’]+$/, '')
    .trim()

function guessShotSize(visual: string): ShotSize {
  const v = visual.toLowerCase()
  if (/over-the-shoulder|over the shoulder/.test(v)) return 'over-the-shoulder'
  if (/top-down|overhead|flat lay/.test(v)) return 'top-down'
  if (/macro/.test(v)) return 'macro'
  if (/close-up|close up|holding .* beside her face/.test(v)) return 'close-up'
  if (/wide/.test(v)) return 'wide'
  return 'medium'
}

export function newScene(patch: Partial<Scene> = {}): Scene {
  return {
    id: uid(),
    title: 'New shot',
    block: 1,
    duration: 5,
    visual: '',
    dialogue: '',
    overlay: '',
    delivery: '',
    prompt: '',
    referenceIds: [],
    primaryAssetId: '',
    voiceAssetId: '',
    shotSize: 'medium',
    cameraMovement: 'handheld',
    lighting: 'Natural daylight from the window',
    framing: 'Vertical 9:16, keep the creator and the product inside the frame.',
    continuity: '',
    extraInstructions: '',
    endFrame: '',
    ...patch,
  }
}

/**
 * Reads a script written like:
 *
 *   REFERENCES: ... FORMAT: ... CONTINUITY: ...
 *   (Shot: 0:00–0:05)
 *   - Visual: ...   - Spoken Line: "..."   - On-Screen Text Overlay: "..."   - Delivery: ...
 *   END FRAME: ...
 *   (next REFERENCES: starts the next generated video)
 *   NEGATIVE PROMPT: ...
 */
interface RawShot {
  start: number
  end: number
  visual: string
  dialogue: string
  overlay: string
  delivery: string
}

export function parseScript(raw: string): Parsed {
  let text = raw.replace(/\r\n?/g, '\n')
  let negative = ''
  const neg = /NEGATIVE PROMPT:\s*([\s\S]*)$/.exec(text)
  if (neg) {
    negative = neg[1].replace(/\s+/g, ' ').trim()
    text = text.slice(0, neg.index)
  }

  const chunks = text
    .split(/(?=REFERENCES:)/)
    .map((c) => c.trim())
    .filter((c) => /\(Shot:/.test(c))

  const scenes: Scene[] = []
  const blocks: BlockInfo[] = []
  let format = ''
  let shotNo = 0

  chunks.forEach((chunk, bi) => {
    const block: BlockInfo = { references: '', continuity: '', endFrame: '' }
    let section: 'references' | 'format' | 'continuity' | 'end' | 'shot' | null = null
    let cur: RawShot | null = null
    let field: 'visual' | 'dialogue' | 'overlay' | 'delivery' | null = null
    const shots: RawShot[] = []
    let blockFormat = ''

    const add = (target: string, line: string) => (target ? target + ' ' + line : line)

    for (const raw of chunk.split('\n')) {
      const line = raw.trim()
      if (!line) continue
      let m: RegExpExecArray | null

      if ((m = /^(REFERENCES|FORMAT|CONTINUITY|END FRAME):\s*(.*)$/.exec(line))) {
        section = ({ REFERENCES: 'references', FORMAT: 'format', CONTINUITY: 'continuity', 'END FRAME': 'end' } as const)[
          m[1] as 'REFERENCES' | 'FORMAT' | 'CONTINUITY' | 'END FRAME'
        ]
        field = null
        if (section === 'end') cur = null
        if (m[2]) {
          if (section === 'references') block.references = add(block.references, m[2])
          if (section === 'format') blockFormat = add(blockFormat, m[2])
          if (section === 'continuity') block.continuity = add(block.continuity, m[2])
          if (section === 'end') block.endFrame = add(block.endFrame, m[2])
        }
        continue
      }

      if ((m = /^\(Shot:\s*([\d:]+)\s*[–—-]\s*([\d:]+)\)/.exec(line))) {
        const shot: RawShot = { start: toSec(m[1]), end: toSec(m[2]), visual: '', dialogue: '', overlay: '', delivery: '' }
        cur = shot
        shots.push(shot)
        section = 'shot'
        field = null
        continue
      }

      if (section === 'shot' && cur) {
        if ((m = /^-\s*Visual:\s*(.*)$/i.exec(line))) {
          field = 'visual'
          cur.visual = m[1]
        } else if ((m = /^-\s*Spoken Line:\s*(.*)$/i.exec(line))) {
          field = 'dialogue'
          cur.dialogue = m[1]
        } else if ((m = /^-\s*On-Screen Text(?: Overlay)?:\s*(.*)$/i.exec(line))) {
          field = 'overlay'
          cur.overlay = m[1]
        } else if ((m = /^-\s*Delivery:\s*(.*)$/i.exec(line))) {
          field = 'delivery'
          cur.delivery = m[1]
        } else if (field) {
          cur[field] = add(cur[field], line)
        }
        continue
      }

      if (section === 'references') block.references = add(block.references, line)
      else if (section === 'format') blockFormat = add(blockFormat, line)
      else if (section === 'continuity') block.continuity = add(block.continuity, line)
      else if (section === 'end') block.endFrame = add(block.endFrame, line)
    }

    if (!format && blockFormat) format = blockFormat
    blocks.push(block)

    shots.forEach((s, k) => {
      shotNo++
      scenes.push(
        newScene({
          title: `Shot ${shotNo} · ${mmss(s.start)}–${mmss(s.end)}`,
          block: bi + 1,
          duration: Math.max(1, Math.round(s.end - s.start)),
          visual: s.visual.trim(),
          dialogue: unquote(s.dialogue),
          overlay: unquote(s.overlay),
          delivery: s.delivery.trim(),
          shotSize: guessShotSize(s.visual),
          continuity: k === 0 ? block.continuity : '',
          endFrame: k === shots.length - 1 ? block.endFrame : '',
        }),
      )
    })
  })

  return { scenes, blocks, format, negative }
}

